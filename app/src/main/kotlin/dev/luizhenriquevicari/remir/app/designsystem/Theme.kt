@Immutable
data class RemirExtendedColors(
    val success: Color,
    val onSuccess: Color,
    val warning: Color,
    val onWarning: Color,
)

private val LightExtended =
    RemirExtendedColors(
        success = successLight,
        onSuccess = onSuccessLight,
        warning = warningLight,
        onWarning = onWarningLight,
    )

private val DarkExtended =
    RemirExtendedColors(
        success = successDark,
        onSuccess = onSuccessDark,
        warning = warningDark,
        onWarning = onWarningDark,
    )

val LocalRemirColors = staticCompositionLocalOf { DarkExtended }

/** App theme. Dynamic color is intentionally off: Monet would erase the brand. */
@Composable
fun RemirTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit,
) {
    val scheme = if (darkTheme) DarkScheme else LightScheme
    val extended = if (darkTheme) DarkExtended else LightExtended

    CompositionLocalProvider(LocalRemirColors provides extended) {
        MaterialTheme(
            colorScheme = scheme,
            typography = RemirTypography,
            shapes = RemirShapes,
            content = content,
        )
    }
}

object RemirTheme {
    val extended: RemirExtendedColors
        @Composable @ReadOnlyComposable
        get() = LocalRemirColors.current
}
